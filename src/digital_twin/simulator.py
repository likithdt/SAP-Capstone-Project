"""
Physical Signal Simulator for Rotating Industrial Asset.
Models nominal 1800 RPM rotating motor telemetry across 7 physical operational classes:
  - Class 0 (Healthy)
  - Class 1 (Bearing Wear - BPFO)
  - Class 2 (Rotor Imbalance - 1X)
  - Class 3 (Shaft Misalignment - 2X/3X)
  - Class 4 (Thermal Overheating)
  - Class 5 (Motor Overload - 100 Hz ripple)
  - Class 6 (Sensor Anomaly - Spikes/Dropouts)
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone, timedelta
from typing import Dict, List, Optional, Tuple, Union, Any
import numpy as np
import pandas as pd
from scipy import signal, stats

from src.config import AssetConfig, ClassThresholds, FaultClass, DEFAULT_ASSET_CONFIG


@dataclass
class TelemetryBatch:
    """Encapsulates a synchronous multi-sensor window generated by the simulator."""
    time: np.ndarray
    accel_x: np.ndarray          # Radial dynamic acceleration (g)
    accel_y: np.ndarray          # Tangential dynamic acceleration (g)
    accel_z: np.ndarray          # Axial dynamic acceleration (g)
    temperature_c: np.ndarray    # Motor temperature (°C)
    current_a: np.ndarray        # Motor current draw (A)
    speed_rpm: np.ndarray        # Asset rotational speed (RPM)
    fault_class: int
    fault_name: str
    sampling_rate_hz: float
    asset_id: str = "MOTOR-001"
    device_id: str = "ESP32-MOTOR-001"
    start_time: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    @property
    def rms_vibration(self) -> float:
        """Root Mean Square of radial vibration accel_x (g)."""
        clean = self.accel_x[~np.isnan(self.accel_x)]
        return float(np.sqrt(np.mean(clean**2))) if len(clean) > 0 else 0.0

    @property
    def peak_vibration(self) -> float:
        """Maximum absolute radial vibration peak (g)."""
        clean = self.accel_x[~np.isnan(self.accel_x)]
        return float(np.max(np.abs(clean))) if len(clean) > 0 else 0.0

    @property
    def crest_factor(self) -> float:
        """Crest Factor = Peak / RMS."""
        rms = self.rms_vibration
        return (self.peak_vibration / rms) if rms > 1e-6 else 0.0

    @property
    def kurtosis(self) -> float:
        """Pearson kurtosis of radial vibration (Gaussian = 3.0)."""
        clean = self.accel_x[~np.isnan(self.accel_x)]
        return float(stats.kurtosis(clean, fisher=False)) if len(clean) > 10 else 0.0

    @property
    def skewness(self) -> float:
        """Skewness of radial vibration."""
        clean = self.accel_x[~np.isnan(self.accel_x)]
        return float(stats.skew(clean)) if len(clean) > 10 else 0.0

    @property
    def mean_temperature(self) -> float:
        """Mean temperature (°C) over the window."""
        clean = self.temperature_c[~np.isnan(self.temperature_c)]
        return float(np.mean(clean)) if len(clean) > 0 else 0.0

    @property
    def mean_current(self) -> float:
        """Mean current (A) over the window."""
        clean = self.current_a[~np.isnan(self.current_a)]
        return float(np.mean(clean)) if len(clean) > 0 else 0.0

    @property
    def mean_speed_rpm(self) -> float:
        """Mean asset speed (RPM)."""
        return float(np.mean(self.speed_rpm))

    def compute_fft(self, signal_name: str = "accel_x") -> Tuple[np.ndarray, np.ndarray]:
        """
        Compute Real-valued Fast Fourier Transform (rFFT) for specified channel.
        Returns: (frequencies_hz, amplitudes)
        """
        data = getattr(self, signal_name)
        clean = np.nan_to_num(data, nan=0.0)
        n = len(clean)
        freqs = np.fft.rfftfreq(n, d=1.0 / self.sampling_rate_hz)
        fft_vals = np.abs(np.fft.rfft(clean)) * (2.0 / n)
        return freqs, fft_vals

    def dominant_frequency(self, signal_name: str = "accel_x") -> float:
        """Return the dominant frequency peak in Hz (excluding DC component)."""
        freqs, amplitudes = self.compute_fft(signal_name)
        if len(amplitudes) <= 1:
            return 0.0
        peak_idx = int(np.argmax(amplitudes[1:])) + 1
        return float(freqs[peak_idx])

    def to_dataframe(self) -> pd.DataFrame:
        """Convert telemetry window into a tabular pandas DataFrame."""
        return pd.DataFrame({
            "time_sec": self.time,
            "accel_x": self.accel_x,
            "accel_y": self.accel_y,
            "accel_z": self.accel_z,
            "temperature_c": self.temperature_c,
            "current_a": self.current_a,
            "speed_rpm": self.speed_rpm,
            "fault_class": self.fault_class,
            "fault_name": self.fault_name,
        })

    def to_mqtt_payloads(self, sample_step: int = 10) -> List[Dict[str, Any]]:
        """
        Serialize telemetry samples into AWS IoT Core compliant JSON payloads.
        Standard ESP32 publishes at e.g. 50-100Hz (sample_step skips redundant samples).
        Matches schema:
          {
            "device_id": "ESP32-MOTOR-001",
            "asset_id": "MOTOR-001",
            "timestamp": "2026-10-23T14:45:00Z",
            "accel_x": 0.42, "accel_y": -0.18, "accel_z": 9.71,
            "temperature_c": 54.8, "current_a": 1.32,
            "rms_vibration": 0.61
          }
        """
        payloads = []
        rms = round(self.rms_vibration, 3)
        for i in range(0, len(self.time), sample_step):
            t_offset = timedelta(seconds=float(self.time[i]))
            ts = (self.start_time + t_offset).strftime("%Y-%m-%dT%H:%M:%S.%fZ")
            
            # Add Earth gravity (9.81 m/s^2 equivalent to ~1g or dynamic 9.81 on Z) for realism
            z_val = self.accel_z[i]
            if not np.isnan(z_val):
                z_with_gravity = round(float(z_val + 9.80), 3)
            else:
                z_with_gravity = None

            payload = {
                "device_id": self.device_id,
                "asset_id": self.asset_id,
                "timestamp": ts,
                "accel_x": None if np.isnan(self.accel_x[i]) else round(float(self.accel_x[i]), 3),
                "accel_y": None if np.isnan(self.accel_y[i]) else round(float(self.accel_y[i]), 3),
                "accel_z": z_with_gravity,
                "temperature_c": None if np.isnan(self.temperature_c[i]) else round(float(self.temperature_c[i]), 2),
                "current_a": None if np.isnan(self.current_a[i]) else round(float(self.current_a[i]), 3),
                "rms_vibration": rms,
                "speed_rpm": round(float(self.speed_rpm[i]), 1),
                "fault_class": self.fault_class,
            }
            payloads.append(payload)
        return payloads

    def summary_metrics(self) -> Dict[str, Any]:
        """Produce dictionary of key diagnostic time & frequency metrics."""
        return {
            "fault_class": self.fault_class,
            "fault_name": self.fault_name,
            "rms_g": round(self.rms_vibration, 4),
            "peak_g": round(self.peak_vibration, 4),
            "crest_factor": round(self.crest_factor, 2),
            "kurtosis": round(self.kurtosis, 2),
            "skewness": round(self.skewness, 2),
            "dominant_freq_hz": round(self.dominant_frequency(), 2),
            "mean_temp_c": round(self.mean_temperature, 2),
            "mean_current_a": round(self.mean_current, 3),
            "speed_rpm": round(self.mean_speed_rpm, 1),
        }


class PhysicalSignalSimulator:
    """
    Precision Physical Signal Simulator for Rotating Assets.
    Generates realistic multi-channel sensor data following rigorous vibration and electrical physics.
    """

    def __init__(self, config: Optional[AssetConfig] = None):
        self.config = config or DEFAULT_ASSET_CONFIG
        self.fs = self.config.sampling_rate_hz
        self.f0 = self.config.fundamental_freq_hz
        self.bpfo = self.config.bpfo_freq_hz
        self.f_line = self.config.line_frequency_hz
        self.nominal_rpm = self.config.nominal_speed_rpm

    def generate_window(
        self,
        fault_class: Union[int, FaultClass],
        duration_sec: float = 1.0,
        speed_rpm: Optional[float] = None,
        seed: Optional[int] = None,
        allow_nan: bool = False,
    ) -> TelemetryBatch:
        """
        Generate a multi-sensor window of specified duration for a given fault class.
        
        Args:
            fault_class: Integer 0-6 or FaultClass enum.
            duration_sec: Window duration in seconds (default: 1.0).
            speed_rpm: Operating speed in RPM (default: nominal 1800 RPM).
            seed: Optional integer seed for reproducibility.
            allow_nan: If True, Class 6 may inject genuine NaNs (default: False).
        """
        fault = FaultClass(fault_class)
        rpm = speed_rpm if speed_rpm is not None else self.nominal_rpm
        rng = np.random.default_rng(seed)

        n_samples = int(duration_sec * self.fs)
        t = np.arange(n_samples) / self.fs

        if fault == FaultClass.HEALTHY:
            batch = self._simulate_class_0_healthy(t, rpm, rng)
        elif fault == FaultClass.BEARING_WEAR:
            batch = self._simulate_class_1_bearing_wear(t, rpm, rng)
        elif fault == FaultClass.ROTOR_IMBALANCE:
            batch = self._simulate_class_2_rotor_imbalance(t, rpm, rng)
        elif fault == FaultClass.SHAFT_MISALIGNMENT:
            batch = self._simulate_class_3_shaft_misalignment(t, rpm, rng)
        elif fault == FaultClass.THERMAL_OVERHEATING:
            batch = self._simulate_class_4_thermal_overheating(t, rpm, rng)
        elif fault == FaultClass.MOTOR_OVERLOAD:
            batch = self._simulate_class_5_motor_overload(t, rpm, rng)
        elif fault == FaultClass.SENSOR_ANOMALY:
            batch = self._simulate_class_6_sensor_anomaly(t, rpm, rng, allow_nan=allow_nan)
        else:
            raise ValueError(f"Unsupported fault class: {fault_class}")

        return batch

    # -------------------------------------------------------------------------
    # Class 0: Healthy Baseline
    # -------------------------------------------------------------------------
    def _simulate_class_0_healthy(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 0 (Healthy):
          - Low-amplitude fundamental vibration at f0 (0.15–0.35 g RMS).
          - Steady baseline temperature (45–52 °C).
          - Nominal idle current (1.1–1.3 A).
        """
        n = len(t)
        f_rot = rpm / 60.0

        # Calibrated fundamental + tiny noise to land strictly inside 0.15 - 0.35 g RMS
        target_rms = rng.uniform(0.20, 0.30)
        amp_1x = target_rms * np.sqrt(2) * 0.90
        v_rad = amp_1x * np.sin(2 * np.pi * f_rot * t + rng.uniform(0, 2 * np.pi))
        v_rad += rng.normal(0, target_rms * 0.25, n)

        # Tangential (accel_y) 90 deg out-of-phase, comparable amplitude
        v_tan = amp_1x * np.sin(2 * np.pi * f_rot * t + np.pi / 2) + rng.normal(0, target_rms * 0.25, n)

        # Axial (accel_z) naturally low in healthy machine (~25-35% of radial)
        v_ax = 0.30 * v_rad + rng.normal(0, 0.03, n)

        # Baseline steady temperature (45–52 °C) with gentle random walk
        base_temp = rng.uniform(47.0, 50.0)
        temp = base_temp + np.cumsum(rng.normal(0, 0.005, n))
        temp = np.clip(temp, 45.5, 51.5)

        # Nominal idle current (1.1–1.3 A) with line ripple
        base_current = rng.uniform(1.15, 1.25)
        current = base_current + 0.02 * np.sin(2 * np.pi * self.f_line * t) + rng.normal(0, 0.015, n)
        current = np.clip(current, 1.10, 1.30)

        speed = np.full(n, rpm) + rng.normal(0, 1.0, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.HEALTHY),
            fault_name=FaultClass.HEALTHY.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 1: Bearing Wear (BPFO)
    # -------------------------------------------------------------------------
    def _simulate_class_1_bearing_wear(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 1 (Bearing Wear):
          - Periodic impact impulses at BPFO (~3.58 * f0 ≈ 107.4 Hz).
          - Produces high kurtosis (> 4.5) and elevated crest factor (> 4.0).
          - Structural ring-down at resonance (~320-360 Hz).
        """
        n = len(t)
        f_rot = rpm / 60.0
        bpfo = self.config.bpfo_factor * f_rot
        t_bpfo = 1.0 / bpfo

        # Structural resonance and decay characteristics
        f_resonance = 340.0
        damping = 1500.0  # Decays sharply within 4-6 ms
        impulse_samples = int(0.006 * self.fs)

        v_impact = np.zeros(n)
        n_impacts = int((t[-1] - t[0]) * bpfo) + 2

        for k in range(n_impacts):
            # Realistic 1-2% slip jitter in ball passage
            jitter = rng.normal(0, 0.015 * t_bpfo)
            t_impact = k * t_bpfo + jitter
            idx = int(t_impact * self.fs)
            if 0 <= idx < n:
                win_len = min(impulse_samples, n - idx)
                tau = np.arange(win_len) / self.fs
                # Physical load-zone modulation by rotational frequency f0
                load_mod = 1.0 + 0.65 * np.cos(2 * np.pi * f_rot * t_impact)
                amp = rng.uniform(4.0, 7.5) * load_mod
                ring_down = amp * np.exp(-damping * tau) * np.sin(2 * np.pi * f_resonance * tau)
                v_impact[idx : idx + win_len] += ring_down

        # Underlying baseline machine vibration
        v_base = 0.16 * np.sqrt(2) * np.sin(2 * np.pi * f_rot * t) + rng.normal(0, 0.025, n)
        v_rad = v_base + v_impact
        v_tan = 0.20 * np.sqrt(2) * np.cos(2 * np.pi * f_rot * t) + 0.6 * v_impact + rng.normal(0, 0.035, n)
        v_ax = 0.35 * v_impact + rng.normal(0, 0.03, n)

        # Bearing wear causes slightly increased friction
        temp = rng.uniform(49.0, 54.0) + np.cumsum(rng.normal(0, 0.005, n))
        current = rng.uniform(1.18, 1.32) + 0.02 * np.sin(2 * np.pi * self.f_line * t) + rng.normal(0, 0.015, n)
        speed = np.full(n, rpm) + rng.normal(0, 1.2, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.BEARING_WEAR),
            fault_name=FaultClass.BEARING_WEAR.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 2: Rotor Imbalance (1X Scaling)
    # -------------------------------------------------------------------------
    def _simulate_class_2_rotor_imbalance(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 2 (Rotor Imbalance):
          - High-amplitude sinusoidal vibration centered strictly at fundamental 1X (30 Hz).
          - Vibration energy strictly scales with rotational speed: amplitude proportional to (N / N0)^2.
        """
        n = len(t)
        f_rot = rpm / 60.0
        speed_ratio = (rpm / self.nominal_rpm) ** 2

        # Nominal imbalance amplitude at 1800 RPM: 1.5 - 2.2 g
        base_amp = rng.uniform(1.5, 2.2) * speed_ratio
        phi = rng.uniform(0, 2 * np.pi)

        v_rad = base_amp * np.sin(2 * np.pi * f_rot * t + phi) + rng.normal(0, 0.06, n)
        v_tan = base_amp * np.cos(2 * np.pi * f_rot * t + phi) + rng.normal(0, 0.06, n)
        
        # Pure radial unbalance creates modest axial reaction
        v_ax = 0.15 * base_amp * np.sin(2 * np.pi * f_rot * t + phi + np.pi / 4) + rng.normal(0, 0.04, n)

        # Imbalance creates slight bearing load and heating (50–60 °C)
        temp = rng.uniform(51.0, 58.0) + np.cumsum(rng.normal(0, 0.005, n))
        current = rng.uniform(1.30, 1.55) + 0.03 * np.sin(2 * np.pi * self.f_line * t) + rng.normal(0, 0.02, n)
        speed = np.full(n, rpm) + rng.normal(0, 1.5, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.ROTOR_IMBALANCE),
            fault_name=FaultClass.ROTOR_IMBALANCE.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 3: Shaft Misalignment (2X/3X Harmonics + Axial)
    # -------------------------------------------------------------------------
    def _simulate_class_3_shaft_misalignment(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 3 (Shaft Misalignment):
          - Strong harmonic peaks at 2X (60 Hz) and 3X (90 Hz).
          - Coupled with moderate phase offset and pronounced axial vibration.
        """
        n = len(t)
        f_rot = rpm / 60.0

        amp_1x = rng.uniform(0.40, 0.70)
        amp_2x = rng.uniform(0.90, 1.40)  # Dominant 2X
        amp_3x = rng.uniform(0.45, 0.80)  # Significant 3X

        phi_1x = rng.uniform(0, 2 * np.pi)
        phi_2x = rng.uniform(0, 2 * np.pi)
        phi_3x = rng.uniform(0, 2 * np.pi)

        v_rad = (
            amp_1x * np.sin(2 * np.pi * f_rot * t + phi_1x)
            + amp_2x * np.sin(4 * np.pi * f_rot * t + phi_2x)
            + amp_3x * np.sin(6 * np.pi * f_rot * t + phi_3x)
            + rng.normal(0, 0.05, n)
        )

        v_tan = (
            amp_1x * np.sin(2 * np.pi * f_rot * t + phi_1x + np.pi / 2)
            + amp_2x * np.sin(4 * np.pi * f_rot * t + phi_2x + np.pi / 2)
            + amp_3x * np.sin(6 * np.pi * f_rot * t + phi_3x + np.pi / 2)
            + rng.normal(0, 0.05, n)
        )

        # Misalignment exerts direct cyclic axial thrust (strong 1X and 2X axial vibration)
        amp_ax_1x = rng.uniform(0.50, 0.90)
        amp_ax_2x = rng.uniform(0.70, 1.20)
        phase_offset = np.pi / 2.0  # Characteristic phase offset
        v_ax = (
            amp_ax_1x * np.sin(2 * np.pi * f_rot * t + phi_1x + phase_offset)
            + amp_ax_2x * np.sin(4 * np.pi * f_rot * t + phi_2x + phase_offset)
            + rng.normal(0, 0.05, n)
        )

        # Coupling friction causes moderate thermal rise (52–63 °C)
        temp = rng.uniform(53.0, 61.0) + np.cumsum(rng.normal(0, 0.005, n))
        current = rng.uniform(1.35, 1.65) + 0.03 * np.sin(2 * np.pi * self.f_line * t) + rng.normal(0, 0.02, n)
        speed = np.full(n, rpm) + rng.normal(0, 1.5, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.SHAFT_MISALIGNMENT),
            fault_name=FaultClass.SHAFT_MISALIGNMENT.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 4: Thermal Overheating
    # -------------------------------------------------------------------------
    def _simulate_class_4_thermal_overheating(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 4 (Thermal Overheating):
          - Progressive thermal drift from ~55 °C climbing beyond 85 °C critical threshold.
          - Mild vibration amplitude modulation due to thermal expansion.
        """
        n = len(t)
        f_rot = rpm / 60.0

        # Monotonic thermal climb past 85 °C
        start_temp = rng.uniform(54.0, 56.5)
        end_temp = rng.uniform(86.5, 93.0)
        temp_profile = np.linspace(start_temp, end_temp, n) + rng.normal(0, 0.15, n)

        # Thermal expansion modulates mechanical vibration amplitude mildly
        temp_ratio = (temp_profile - 55.0) / 30.0  # Scales from 0.0 to ~1.2
        mod_factor = 1.0 + 0.35 * temp_ratio

        base_rad = 0.25 * np.sqrt(2) * np.sin(2 * np.pi * f_rot * t) + rng.normal(0, 0.04, n)
        v_rad = base_rad * mod_factor
        v_tan = (0.25 * np.sqrt(2) * np.cos(2 * np.pi * f_rot * t) + rng.normal(0, 0.04, n)) * mod_factor
        v_ax = (0.10 * np.sin(2 * np.pi * f_rot * t) + rng.normal(0, 0.03, n)) * mod_factor

        # Increased winding resistance causes current drift
        current = rng.uniform(1.35, 1.70) + 0.02 * np.sin(2 * np.pi * self.f_line * t) + rng.normal(0, 0.02, n)
        speed = np.full(n, rpm) + rng.normal(0, 1.8, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp_profile,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.THERMAL_OVERHEATING),
            fault_name=FaultClass.THERMAL_OVERHEATING.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 5: Motor Overload
    # -------------------------------------------------------------------------
    def _simulate_class_5_motor_overload(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator
    ) -> TelemetryBatch:
        """
        Class 5 (Motor Overload):
          - High current draw (2.4–3.8 A vs. 1.2 A nominal).
          - Frequency line ripples at 2 * 50 Hz = 100 Hz.
          - Lagging thermal rise due to thermal mass/inertia.
        """
        n = len(t)
        f_rot = rpm / 60.0

        # Mean current in [2.4, 3.8] A
        mean_current = rng.uniform(2.7, 3.5)
        ripple_freq = 2.0 * self.f_line  # 100 Hz line ripple
        ripple_amp = rng.uniform(0.25, 0.45)
        current = (
            mean_current
            + ripple_amp * np.sin(2 * np.pi * ripple_freq * t + rng.uniform(0, 2 * np.pi))
            + rng.normal(0, 0.03, n)
        )

        # Lagging thermal rise (first-order thermal step response: tau ~ thermal mass)
        tau_seconds = 2.5
        t_elapsed = t - t[0]
        initial_temp = rng.uniform(49.0, 52.0)
        target_temp = rng.uniform(70.0, 82.0)
        temp = initial_temp + (target_temp - initial_temp) * (1.0 - np.exp(-t_elapsed / tau_seconds))
        temp += rng.normal(0, 0.1, n)

        # Electromagnetic hum at 100 Hz ripple and increased torque load vibration
        v_rad = (
            0.40 * np.sin(2 * np.pi * f_rot * t)
            + 0.50 * np.sin(2 * np.pi * ripple_freq * t)
            + rng.normal(0, 0.07, n)
        )
        v_tan = (
            0.40 * np.cos(2 * np.pi * f_rot * t)
            + 0.35 * np.cos(2 * np.pi * ripple_freq * t)
            + rng.normal(0, 0.07, n)
        )
        v_ax = 0.25 * np.sin(2 * np.pi * ripple_freq * t) + rng.normal(0, 0.04, n)

        # Under heavy load, induction motor experiences slight slip (RPM decreases slightly)
        speed = np.full(n, rpm - rng.uniform(25.0, 50.0)) + rng.normal(0, 2.0, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.MOTOR_OVERLOAD),
            fault_name=FaultClass.MOTOR_OVERLOAD.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Class 6: Sensor Anomaly (Spikes, Dropouts, Noise Saturation)
    # -------------------------------------------------------------------------
    def _simulate_class_6_sensor_anomaly(
        self, t: np.ndarray, rpm: float, rng: np.random.Generator, allow_nan: bool = False
    ) -> TelemetryBatch:
        """
        Class 6 (Sensor Anomaly):
          - Signal dropouts (zero-hold/flatlines simulating loose wiring).
          - Random float spikes (> 15 g or NaN).
          - White noise saturation simulating ADC glitches or loose ground.
        """
        n = len(t)
        f_rot = rpm / 60.0

        # Start with standard signal
        v_rad = 0.25 * np.sin(2 * np.pi * f_rot * t) + rng.normal(0, 0.05, n)
        v_tan = 0.25 * np.cos(2 * np.pi * f_rot * t) + rng.normal(0, 0.05, n)
        v_ax = 0.10 * np.sin(2 * np.pi * f_rot * t) + rng.normal(0, 0.04, n)
        temp = np.full(n, 48.0) + rng.normal(0, 0.2, n)
        current = np.full(n, 1.2) + rng.normal(0, 0.02, n)

        # 1. White noise saturation segment (ADC rail saturation / loose shield)
        sat_start = int(0.15 * n)
        sat_end = int(0.35 * n)
        v_rad[sat_start:sat_end] += rng.normal(0, 3.5, sat_end - sat_start)

        # 2. Random float spikes (> 15 g)
        num_spikes = rng.integers(3, 7)
        spike_indices = rng.choice(n, size=num_spikes, replace=False)
        for idx in spike_indices:
            spike_val = rng.uniform(16.0, 24.0) * rng.choice([-1.0, 1.0])
            v_rad[idx] = spike_val
            if rng.random() > 0.5:
                v_tan[idx] = spike_val * 0.8

        # 3. Signal dropouts (loose wire disconnection causing zero-hold or flatline)
        drop_len = int(rng.uniform(0.08, 0.15) * n)
        drop_start = int(0.55 * n)
        v_rad[drop_start : drop_start + drop_len] = 0.0
        v_tan[drop_start : drop_start + drop_len] = 0.0

        # 4. Optional NaN injection if allow_nan is True
        if allow_nan:
            nan_indices = rng.choice(n, size=3, replace=False)
            v_rad[nan_indices] = np.nan
            temp[nan_indices[0]] = np.nan
            current[nan_indices[1]] = np.nan

        speed = np.full(n, rpm) + rng.normal(0, 1.0, n)

        return TelemetryBatch(
            time=t,
            accel_x=v_rad,
            accel_y=v_tan,
            accel_z=v_ax,
            temperature_c=temp,
            current_a=current,
            speed_rpm=speed,
            fault_class=int(FaultClass.SENSOR_ANOMALY),
            fault_name=FaultClass.SENSOR_ANOMALY.label,
            sampling_rate_hz=self.fs,
            asset_id=self.config.asset_id,
            device_id=self.config.device_id,
        )

    # -------------------------------------------------------------------------
    # Dataset Generation Utility
    # -------------------------------------------------------------------------
    def generate_dataset(
        self,
        samples_per_class: int = 50,
        duration_sec: float = 1.0,
        seed: int = 42,
        output_dir: Optional[str] = "data/raw",
    ) -> pd.DataFrame:
        """
        Generate a multi-class synthetic dataset across all 7 operational modes.
        Computes window summary statistics and can persist dataset for model training.
        """
        records = []
        rng = np.random.default_rng(seed)

        for fault in FaultClass:
            for s in range(samples_per_class):
                # Apply small operating speed fluctuation around 1800 RPM
                speed_jitter = rng.uniform(-15.0, 15.0)
                batch = self.generate_window(
                    fault_class=fault,
                    duration_sec=duration_sec,
                    speed_rpm=self.nominal_rpm + speed_jitter,
                    seed=int(rng.integers(1, 1000000)),
                    allow_nan=False,
                )
                
                # Extract summary diagnostics
                metrics = batch.summary_metrics()
                metrics["sample_id"] = f"{fault.name.lower()}_{s:04d}"
                records.append(metrics)

        df = pd.DataFrame(records)
        if output_dir:
            import os
            os.makedirs(output_dir, exist_ok=True)
            csv_path = os.path.join(output_dir, "synthetic_asset_metrics.csv")
            df.to_csv(csv_path, index=False)
        return df


